# if statement
x = 10
if x > 5:
    print("x is greater than 5")

# if-else statement
y = 3
if y > 5:
    print("y is greater than 5")
else:
    print("y is not greater than 5")

# if-elif-else statement
z = 7
if z > 5:
    print("z is greater than 5")
elif z == 5:
    print("z is equal to 5")
else:
    print("z is not greater than 5")